#!/usr/bin/env node
/**
 * Bundle the Liquid Glass Optics built-in background chart as data URLs.
 *
 * Electron loads the renderer from file://, where WebGL refuses textures from
 * cross-origin <img> elements. Embedding the WebP pair as data URLs keeps the
 * optical "image" background working under the renderer CSP (`img-src data:`).
 *
 * Source: ~/.claude/skills/liquid-glass-optics/assets/core/backgrounds
 * Output: src/js/glass-backgrounds.js
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.resolve(__dirname, '..');
const skillRoot =
  process.env.LIQUID_GLASS_OPTICS_SKILL ||
  path.join(os.homedir(), '.claude', 'skills', 'liquid-glass-optics');
const sourceDir = path.join(skillRoot, 'assets', 'core', 'backgrounds');
const target = path.join(root, 'src', 'js', 'glass-backgrounds.js');

function read(name) {
  const file = path.join(sourceDir, name);
  if (!fs.existsSync(file)) {
    console.error(`Missing background image: ${file}`);
    process.exit(1);
  }
  return fs.readFileSync(file).toString('base64');
}

const light = read('optical-light.webp');
const dark = read('optical-dark.webp');

const output = `/* Generated by scripts/build-glass-backgrounds.js — do not edit by hand. */
export const GLASS_BACKGROUND_IMAGES = {
  light: 'data:image/webp;base64,${light}',
  dark: 'data:image/webp;base64,${dark}',
};
`;

fs.writeFileSync(target, output);
console.log(`Wrote ${path.relative(root, target)} (${Math.round(output.length / 1024)} KiB)`);
